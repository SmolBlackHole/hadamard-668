"""Exhaustive checks for blockwise integrability of the GS4 flip operator.

This is a research prototype, not production code.
"""

from __future__ import annotations

from itertools import product

import numpy as np

from src.tracker import Tracker


def edge_word(x: np.ndarray) -> np.ndarray:
    """Return p[c] = x[c] * x[c+1] for the antiperiodic extension."""
    return x * np.concatenate((x[1:], -x[:1]))


def block_from_edges(p: np.ndarray) -> np.ndarray:
    """Construct one sequence's complete reduced flip block from its edges."""
    n = len(p)
    m = (n - 1) // 2
    # cumprod over all cyclic windows; the loop is only over research-scale lags.
    forward = np.empty((n, m), dtype=np.int8)
    running = np.ones(n, dtype=np.int8)
    for t in range(1, m + 1):
        running *= p[(np.arange(n) + t - 1) % n]
        forward[:, t - 1] = running
    backward = forward[(np.arange(n)[:, None] - np.arange(1, m + 1)) % n, np.arange(m)]
    return (-(forward + backward) // 2).astype(np.int8)


def block_from_sequence(x: np.ndarray) -> np.ndarray:
    return block_from_edges(edge_word(x))


def candidate_edges(first_column: np.ndarray) -> list[np.ndarray]:
    """Solve d[c,1] = -(p[c-1] + p[c]) / 2 with product(p) = -1."""
    answers: list[np.ndarray] = []
    for initial in (-1, 1):
        p = np.empty(len(first_column), dtype=np.int8)
        p[0] = initial
        valid = True
        for c in range(1, len(p)):
            d = int(first_column[c])
            if d == 0:
                p[c] = -p[c - 1]
            elif d in (-1, 1) and p[c - 1] == -d:
                p[c] = -d
            else:
                valid = False
                break
        if not valid or first_column[0] != -(p[-1] + p[0]) // 2:
            continue
        if int(np.prod(p, dtype=np.int64)) != -1:
            continue
        if not any(np.array_equal(p, previous) for previous in answers):
            answers.append(p)
    return answers


def is_integrable(block: np.ndarray) -> bool:
    return any(np.array_equal(block_from_edges(p), block) for p in candidate_edges(block[:, 0]))


def exhaustive(max_n: int = 12) -> None:
    for n in range(3, max_n + 1):
        by_first: dict[bytes, set[bytes]] = {}
        blocks: set[bytes] = set()
        for bits in product((-1, 1), repeat=n):
            x = np.asarray(bits, dtype=np.int8)
            p = edge_word(x)
            block = block_from_sequence(x)
            assert int(np.prod(p, dtype=np.int64)) == -1
            assert np.array_equal(block, block_from_edges(p))
            assert is_integrable(block)
            blocks.add(block.tobytes())
            by_first.setdefault(block[:, 0].tobytes(), set()).add(block.tobytes())

        edge_words = {
            np.asarray(bits, dtype=np.int8).tobytes()
            for bits in product((-1, 1), repeat=n)
            if np.prod(bits) == -1
        }
        first_words = set(by_first)
        assert len(blocks) == len(edge_words) - (1 if n % 4 == 2 else 0)
        assert len(first_words) == len(blocks)
        assert all(len(completions) == 1 for completions in by_first.values())

        # Full ternary enumeration verifies that the two-state reconstruction
        # recognizes exactly the first columns generated by odd-parity edges.
        if n <= 10:
            recognized = {
                np.asarray(word, dtype=np.int8).tobytes()
                for word in product((-1, 0, 1), repeat=n)
                if candidate_edges(np.asarray(word, dtype=np.int8))
            }
            assert recognized == first_words

        print(
            f"n={n:2d} edge_words={len(edge_words):5d} "
            f"first_columns={len(first_words):5d} blocks={len(blocks):5d}"
        )


def tracker_check() -> None:
    rng = np.random.default_rng(20260807)
    for n in range(3, 54):
        seqs = rng.choice((-1, 1), size=(4, n)).astype(np.int8)
        tracker = Tracker()
        tracker.build(seqs)
        assert tracker._delta is not None
        width = (n - 1) // 2
        expected = np.vstack([block_from_sequence(x) for x in seqs])
        assert np.array_equal(expected, tracker._delta[:, :width])


if __name__ == "__main__":
    tracker_check()
    exhaustive()
